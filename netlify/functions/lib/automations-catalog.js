// ---------- helpers ----------

const BY_ID = new Map(ENTRIES.map((e) => [e.id, e]));

function byId(id) {
  return BY_ID.get(id) || null;
}

// First smtp/direct entry carrying a deliverEmail / direct-send
// kind. Kinds are shared in exactly one place today
// (signup_confirmation, plain + claim variant): the plain entry is
// listed first, so it wins — callers that need the claim variant
// look it up by id.
function entryForKind(kind) {
  for (const e of ENTRIES) {
    if ((e.lane === "smtp" || e.lane === "direct") && e.kind === kind) return e;
  }
  return null;
}

function entryForRail(eventType) {
  for (const e of ENTRIES) {
    if (e.lane === "rail" && e.kind === eventType) return e;
  }
  return null;
}

// Kinds that can never be turned off (Area 1 hard rule): people are
// locked out or left uninformed without them. Derived from the
// entries so the flag lives in exactly one place. Note the seat
// invite is NOT in here: its catalogue kind is partner_seat_invite,
// not password_reset, even though it rides that lane underneath.
const CRITICAL_KINDS = new Set(ENTRIES.filter((e) => e.critical).map((e) => e.kind));

module.exports = { ENTRIES, GROUPS, byId, entryForKind, entryForRail, CRITICAL_KINDS };
