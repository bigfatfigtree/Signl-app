// Automation catalogue (Build -138, Admin Expansion Area 1 + Area 6).
//
// One entry per automatic email / text the system sends today. This
// module is PURE DATA + helpers: no store require, no I/O, so the
// Automations room, the Template Studio, the send funnel's on/off
// check, and the verify suite can all read the same list cheaply.
//
// The catalogue is code, reviewed like code (spec, Area 1): a new
// automation that ships without an entry here fails verify.
//
// Entry shape:
//   { id, name (plain words), group, trigger (plain words),
//     recipient (plain words),
//     lane: "smtp" | "rail" | "direct",
//     kind (the deliverEmail kind, the rail event type, or the
//           direct-send id),
//     templateRef (same as id — the Template Studio record key),
//     prefGate: null | "recipient settings",
//     critical: bool,
//     editLevel: "full" | "subject" | "view",
//     requiredTokens: [...] }
//
// editLevel (Area 6 decomposition — what the Template Studio may
// change):
//   "full"    subject + body are plain builder strings with tokens;
//             the override layer may replace them.
//   "subject" the subject pattern is overridable, the body is not —
//             it is computed from the record at send time (a
//             checklist, a band, a missing-fields list) or carries a
//             per-send secret link that must never be templated.
//   "view"    preview + test-send only in v1: the body is assembled
//             from booking / call-site data across call sites.
//
// Groups are Jeff's mental model, never the code lane (Area 1 UX
// lens): Joining / Account / Visits and posts / Deals and licences /
// Trouble. GROUPS below is the display order.

